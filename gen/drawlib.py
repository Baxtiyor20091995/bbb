class Canvas:
    def __init__(self, w, h, bg=(255, 255, 255)):
        self.w = w
        self.h = h
        self.buf = bytearray()
        r, g, b = bg
        row = bytes((r, g, b)) * w
        for _ in range(h):
            self.buf += row

    def set(self, x, y, color):
        x = int(round(x))
        y = int(round(y))
        if 0 <= x < self.w and 0 <= y < self.h:
            i = (y * self.w + x) * 3
            self.buf[i] = color[0]
            self.buf[i + 1] = color[1]
            self.buf[i + 2] = color[2]

    def dot(self, x, y, color, r=1):
        for dy in range(-r, r + 1):
            for dx in range(-r, r + 1):
                if dx * dx + dy * dy <= r * r:
                    self.set(x + dx, y + dy, color)

    def line(self, x0, y0, x1, y1, color, w=1):
        x0, y0, x1, y1 = map(float, (x0, y0, x1, y1))
        dx = abs(x1 - x0)
        dy = abs(y1 - y0)
        steps = int(max(dx, dy)) + 1
        for i in range(steps + 1):
            t = i / steps
            x = x0 + (x1 - x0) * t
            y = y0 + (y1 - y0) * t
            self.dot(x, y, color, r=max(0, w // 2))

    def rect(self, x0, y0, x1, y1, color=None, fill=None, w=2):
        if fill is not None:
            xa, xb = sorted((int(x0), int(x1)))
            ya, yb = sorted((int(y0), int(y1)))
            for y in range(ya, yb + 1):
                for x in range(xa, xb + 1):
                    self.set(x, y, fill)
        if color is not None:
            self.line(x0, y0, x1, y0, color, w)
            self.line(x1, y0, x1, y1, color, w)
            self.line(x1, y1, x0, y1, color, w)
            self.line(x0, y1, x0, y0, color, w)

    def circle(self, cx, cy, rad, color=None, fill=None, w=2):
        if fill is not None:
            for y in range(int(cy - rad), int(cy + rad) + 1):
                for x in range(int(cx - rad), int(cx + rad) + 1):
                    if (x - cx) ** 2 + (y - cy) ** 2 <= rad * rad:
                        self.set(x, y, fill)
        if color is not None:
            n = int(2 * math.pi * rad) + 8
            for i in range(n + 1):
                a = 2 * math.pi * i / n
                self.dot(cx + rad * math.cos(a), cy + rad * math.sin(a), color,
                         r=max(0, w // 2))

    def arrow(self, x0, y0, x1, y1, color, w=2, head=9):
        self.line(x0, y0, x1, y1, color, w)
        ang = math.atan2(y1 - y0, x1 - x0)
        for da in (math.radians(150), math.radians(-150)):
            hx = x1 + head * math.cos(ang + da)
            hy = y1 + head * math.sin(ang + da)
            self.line(x1, y1, hx, hy, color, w)

    def text(self, x, y, s, color=(0, 0, 0), scale=2, spacing=1):
        s = s.upper()
        cx = x
        for ch in s:
            glyph = FONT.get(ch, FONT[" "])
            for ry, rowbits in enumerate(glyph):
                for rx, bit in enumerate(rowbits):
                    if bit == "1":
                        px = cx + rx * scale
                        py = y + ry * scale
                        for ddy in range(scale):
                            for ddx in range(scale):
                                self.set(px + ddx, py + ddy, color)
            cx += (5 + spacing) * scale

    def text_w(self, s, scale=2, spacing=1):
        return len(s) * (5 + spacing) * scale

    def ctext(self, cx, y, s, color=(0, 0, 0), scale=2, spacing=1):
        """Текст, центрированный по горизонтали относительно cx."""
        w = self.text_w(s, scale, spacing)
        self.text(cx - w // 2, y, s, color, scale, spacing)

    def save_png(self, path):
        raw = bytearray()
        stride = self.w * 3
        for y in range(self.h):
            raw.append(0)  # filter type 0
            raw += self.buf[y * stride:(y + 1) * stride]
        comp = zlib.compress(bytes(raw), 9)

        def chunk(typ, data):
            c = struct.pack(">I", len(data)) + typ + data
            crc = zlib.crc32(typ + data) & 0xffffffff
            return c + struct.pack(">I", crc)

        sig = b"\x89PNG\r\n\x1a\n"
        ihdr = struct.pack(">IIBBBBB", self.w, self.h, 8, 2, 0, 0, 0)
        with open(path, "wb") as f:
            f.write(sig)
            f.write(chunk(b"IHDR", ihdr))
            f.write(chunk(b"IDAT", comp))
            f.write(chunk(b"IEND", b""))


