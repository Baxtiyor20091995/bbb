def refitem(d, num, text):
    """Библиографическая запись: висячий отступ, нумерация вручную."""
    d.blocks.append(
        '<w:p><w:pPr><w:ind w:left="567" w:hanging="567"/>'
        '<w:jc w:val="both"/>'
        '<w:spacing w:line="360" w:lineRule="auto" w:after="40"/>'
        '<w:rPr><w:sz w:val="28"/></w:rPr></w:pPr>'
        f'<w:r><w:rPr><w:sz w:val="28"/></w:rPr>'
        f'<w:t xml:space="preserve">{escape(str(num) + ". " + text)}</w:t>'
        '</w:r></w:p>')


